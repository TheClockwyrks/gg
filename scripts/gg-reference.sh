#!/usr/bin/env bash
#
# Project gg's model-facing reference into a directory the backend can serve.
#
#   scripts/gg-reference.sh [OUT_DIR]        # default: target/gg-reference
#
# WHAT IT WRITES. Twelve documents: `index.json` — every tool gg can offer a model, with the real
# description and parameter schema that go on the wire, grouped into gg's families, plus a line per
# program language — and one `<language>.json` per arm, carrying every responses-as-code function and
# type on that arm with the bytes that arm's own documentation view renders for a model. Not a
# paraphrase of any of it: the tools come out of a maximal `ToolRegistry` and each entry's body out
# of the same `DocsRuntime::read` a program's own lookup goes through.
#
# WHO SERVES IT. `tcab-backend`, at `GET /gg/reference` and `GET /gg/reference/{language}`, reading
# the directory `TCAB_GG_REFERENCE` names. That indirection is the whole reason this script exists:
# the backend must not depend on `test-cabinet-gg` — oxc and tiktoken-rs are nowhere in that server's
# dependency tree, and building gg reflects eleven SDKs' catalogues with eleven language toolchains,
# which would become a prerequisite for compiling the backend — so the projection crosses the crate
# boundary as files beside the binary, exactly as `packages/browser-driver` does for the Playwright
# driver the backend also ships and never links.
#
# WHERE THE DOCUMENTS COME FROM — two places, the two `docs/reference.md` ("Serving the documents")
# names:
#
#   1. GG'S PIPELINE. Each `gg_<arch>` job builds gg and runs `scripts/ci/gg-dist.sh`, which projects
#      the documents with `gg reference --out` from the very binary it just linked and packs them as
#      `gg-reference.tar.gz` beside it. A `v*` tag's run publishes that tarball to the release
#      container as `v<version>/gg-reference.tar.gz`, and the backend image fetches the one of the
#      version the driver pins, unpacks it at /opt/gg-reference and points TCAB_GG_REFERENCE there.
#      So a deployed console's reference and the harness its runs execute describe one release, and
#      there is nothing committed to gate and no version skew to detect — which is why the artifact
#      this replaced (`crates/backend/src/gg_reference.json`, regenerated by `npm run gen:contract`
#      and diffed by `scripts/ci/contract-drift.sh`) is gone rather than regenerated. A backend run
#      from a release tarball unpacks the same object and points the variable at it.
#
#   2. A DEVELOPER running the backend as a bare process from a checkout (the path
#      `development/running.md` documents), who has no image to bake anything. This script, run in
#      the gg checkout, writes the documents to that checkout's `target/gg-reference/` by default,
#      which is the directory that page has `.env.backend` name as TCAB_GG_REFERENCE:
#
#          scripts/gg-reference.sh                  # -> target/gg-reference/
#          scripts/gg-reference.sh /tmp/reference   # -> anywhere else, then point TCAB_GG_REFERENCE at it
#
#      Without them the reference endpoints answer 503 with a message naming this script, and nothing
#      else about the backend is affected — a backend with no reference still serves runs, reviews
#      and the catalog.
#
# WHAT IT NEEDS: whatever BUILDING gg needs, and nothing else. Running the projection needs no
# toolchain at all — every arm's signature catalogue is compiled into the binary by
# `crates/gg/build.rs` — but compiling gg reflects all eleven of them out of their guest SDKs and
# builds every arm's artifacts, so this is `scripts/ci/install-gg-toolchains.sh` +
# `scripts/ci/install-gg-build-toolchains.sh` territory. The devcontainer has run both. On a machine
# that has not, the cargo build below stops inside a build script with a sentence naming the tool
# that is missing.
#
# It reaches no network, opens no socket and reads no configuration; that purity is what lets the
# release project the documents from a freshly linked static binary and get the same twelve files on
# every architecture.
set -euo pipefail

# Repo root, independent of the caller's working directory — `cargo run` below is resolved against
# the workspace, and a relative OUT_DIR is resolved against this rather than against wherever the
# caller happened to be standing.
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

# The default lives under `target/`, which is gitignored and is where every other build output in
# this repository goes, so nothing here can be committed by any arrangement of `git add`. It is the
# CHECKOUT's `target/`, not cargo's: a developer who sets `CARGO_TARGET_DIR` elsewhere puts compiled
# artifacts on another disk entirely and these twelve documents still land here, at the one path
# `development/running.md` names for TCAB_GG_REFERENCE.
OUT_DIR="${1:-target/gg-reference}"

# `gg reference --out` creates the directory itself and writes `index.json` LAST, so a directory that
# exists at all is one whose index does not promise an arm that is not beside it. Nothing is emptied
# first: re-running over a previous projection overwrites all twelve files, and the language list is
# a compile-time constant of the binary rather than something an arm could fail to contribute.
cargo run --quiet -p test-cabinet-gg --bin gg -- reference --out "$OUT_DIR"

echo
echo "Wrote gg's reference to $OUT_DIR:"
for document in "$OUT_DIR"/*.json; do
	printf '  %-24s %8s bytes\n' "$(basename "$document")" "$(wc -c <"$document")"
done
